#!/usr/bin/env node
// RD-02: writes supabase/demo/prod-demo.sql — the public demo project for production, built from
// the same fixtures as the local seed. Unlike supabase/seed.sql it creates NO login: the owner
// account has no password and no identity, so the repo's demo credentials never work on prod.
// Idempotent (on conflict do nothing) and wrapped in a transaction; run it in the Supabase SQL editor.
// Usage: node scripts/generate-prod-demo.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const fixture = JSON.parse(readFileSync("src/fixtures/papers.json", "utf8"));
const OWNER_ID = "00000000-0000-4000-8000-0000000000d0";
const JOIN_CODE = "DEMO42"; // must match DEMO_JOIN_CODE in src/components/projects/open-demo-button.tsx
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const { project, papers } = fixture;

const sql = `-- GENERATED by scripts/generate-prod-demo.mjs from src/fixtures/papers.json — do not edit by hand.
-- Production demo project (RD-02). No login is created: the owner has no password or identity.
-- Safe to run more than once. Paste into Supabase → SQL Editor → Run.
begin;

-- Owner account (cannot sign in: no password, no identity)
insert into auth.users (instance_id, id, aud, role, email, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)
values (
  '00000000-0000-0000-0000-000000000000', '${OWNER_ID}', 'authenticated', 'authenticated',
  'demo-owner@papercut.invalid', '{"provider":"email","providers":[]}', '{"full_name":"PaperCut demo"}', now(), now()
)
on conflict (id) do nothing;

-- Demo project (owner membership is added by the on_project_created trigger)
insert into public.projects (id, owner_id, title, query, context, join_code) values (
  ${q(project.id)}, '${OWNER_ID}', ${q(project.title)}, ${q(project.query)}, ${j(project.context)}, '${JOIN_CODE}'
)
on conflict (id) do nothing;

-- Fixture papers (real OpenAlex records); keep any fresher cached copy
insert into public.papers (id, source, external_id, doi, data) values
${papers.map(({ paper: p }) => `  (${q(p.id)}, ${q(p.source)}, ${q(p.externalId)}, ${q(p.doi)}, ${j(p)})`).join(",\n")}
on conflict do nothing;

-- Analyses + computed credibility for the demo project
insert into public.paper_analyses (project_id, paper_id, analysis, credibility) values
${papers.map(({ paper: p, analysis: a, credibility: c }) => `  (${q(project.id)}, ${q(p.id)}, ${j(a)}, ${j(c)})`).join(",\n")}
on conflict do nothing;

-- Starter swipes by the owner so the library and exports aren't empty
insert into public.swipes (project_id, paper_id, user_id, decision) values
${papers
  .slice(0, 6)
  .map(
    ({ paper: p }, i) =>
      `  (${q(project.id)}, ${q(p.id)}, '${OWNER_ID}', '${i === 3 ? "skip" : "save"}')`,
  )
  .join(",\n")}
on conflict do nothing;

commit;

-- Check: expect 1 project, 20 papers, 20 analyses, 5 saves.
select
  (select count(*) from public.projects where join_code = '${JOIN_CODE}') as projects,
  (select count(*) from public.paper_analyses where project_id = ${q(project.id)}) as analyses,
  (select count(*) from public.swipes where project_id = ${q(project.id)} and decision = 'save') as saves;
`;

mkdirSync("supabase/demo", { recursive: true });
writeFileSync("supabase/demo/prod-demo.sql", sql);
console.log(`✅ supabase/demo/prod-demo.sql written (${papers.length} papers)`);
