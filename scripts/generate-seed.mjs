#!/usr/bin/env node
// Regenerates supabase/seed.sql from src/fixtures/papers.json so every local stack opens with
// the same demo data. Run after editing fixtures: node scripts/generate-seed.mjs && pnpm db:reset
import { readFileSync, writeFileSync } from "node:fs";

const fixture = JSON.parse(readFileSync("src/fixtures/papers.json", "utf8"));
const DEMO_USER_ID = "00000000-0000-4000-8000-0000000000d0";
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const j = (v) => `${q(JSON.stringify(v))}::jsonb`;
const { project, papers } = fixture;

const sql = `-- GENERATED by scripts/generate-seed.mjs from src/fixtures/papers.json — do not edit by hand.
-- Demo login (local only): demo@papercut.local / papercut-demo

-- Demo user (+ email identity so password sign-in works)
insert into auth.users (
  instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
  confirmation_token, recovery_token, email_change, email_change_token_new
) values (
  '00000000-0000-0000-0000-000000000000', '${DEMO_USER_ID}', 'authenticated', 'authenticated',
  'demo@papercut.local', extensions.crypt('papercut-demo', extensions.gen_salt('bf')), now(),
  '{"provider":"email","providers":["email"]}', '{"full_name":"Demo Student"}', now(), now(),
  '', '', '', ''
);
insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (
  gen_random_uuid(), '${DEMO_USER_ID}', '${DEMO_USER_ID}',
  '{"sub":"${DEMO_USER_ID}","email":"demo@papercut.local","email_verified":true}', 'email', now(), now(), now()
);

-- Demo project (owner membership is added by the on_project_created trigger)
insert into public.projects (id, owner_id, title, query, context, join_code) values (
  ${q(project.id)}, '${DEMO_USER_ID}', ${q(project.title)}, ${q(project.query)}, ${j(project.context)}, 'DEMO42'
);

-- Fixture papers (real OpenAlex records)
insert into public.papers (id, source, external_id, doi, data) values
${papers.map(({ paper: p }) => `  (${q(p.id)}, ${q(p.source)}, ${q(p.externalId)}, ${q(p.doi)}, ${j(p)})`).join(",\n")};

-- Analyses + computed credibility for the demo project
insert into public.paper_analyses (project_id, paper_id, analysis, credibility) values
${papers.map(({ paper: p, analysis: a, credibility: c }) => `  (${q(project.id)}, ${q(p.id)}, ${j(a)}, ${j(c)})`).join(",\n")};

-- A few swipes so the library and reading list aren't empty
insert into public.swipes (project_id, paper_id, user_id, decision) values
${papers
  .slice(0, 6)
  .map(
    ({ paper: p }, i) =>
      `  (${q(project.id)}, ${q(p.id)}, '${DEMO_USER_ID}', '${i === 3 ? "skip" : "save"}')`,
  )
  .join(",\n")};
`;

writeFileSync("supabase/seed.sql", sql);
console.log(`✅ supabase/seed.sql written (${papers.length} papers)`);
